interface EventSession {
  date: string;
  time?: string;
  note?: string;
}

interface EventCommon {
  slug: string;
  title: string;
  type: EventType;
  status: EventStatus;
  /** ISO-дата начала; без неё событие показывается как «скоро». */
  startDate?: string;
  endDate?: string;
  dateLabel?: string;
  time?: string;
  location?: string;
  age?: string;
  capacity?: number;
  price?: { base: number; student?: number; deposit?: number };
  sessions?: readonly EventSession[];
  description: string;
  registrationUrl?: string;
  nextIntakeLabel?: string;
  report?: readonly string[];
  gallery?: readonly { image: ImageMetadata; alt: string }[];
}

/** Событие, страница которого сверстана шаблоном unlimited position. */
interface StandardEvent extends EventCommon {
  page?: undefined;
}

/** Прошедшие события perfeed: страницы сохраняют исходный дизайн и собственную структуру контента. */
interface PerfeedLaboratoryEvent extends EventCommon {
  page: 'perfeed-laboratory';
  perfeed: typeof zolotoLaboratoryContent;
}

interface PerfeedJamEvent extends EventCommon {
  page: 'perfeed-jam';
  perfeed: {
    announcement: {
      opening: string;
      intro: string;
      duration: string;
      roles: readonly (readonly [string, string])[];
      collaboration: string;
      artist: { name: string; bio: readonly string[] };
    };
    images: { hero: ImageMetadata; artist: ImageMetadata };
  };
}

